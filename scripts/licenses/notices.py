def cargo_components(manifest: dict) -> list[Component]:
    seen: dict[tuple[str, str], Component] = {}
    used_by: dict[tuple[str, str], set[str]] = {}
    for ws in CARGO_WORKSPACES:
        out = subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--manifest-path", os.path.join(REPO, ws)],
            cwd=REPO, text=True,
        )
        meta = json.loads(out)
        for pkg in meta["packages"]:
            if pkg.get("source") is None:
                continue
            k = (pkg["name"], pkg["version"])
            used_by.setdefault(k, set()).add(ws)
            if k in seen:
                continue
            directory = os.path.dirname(pkg["manifest_path"])
            files = license_files(directory)
            if pkg.get("license_file"):
                lf = os.path.join(directory, pkg["license_file"])
                if os.path.isfile(lf) and not any(n == os.path.basename(lf) for n, _ in files):
                    files.append((pkg["license_file"], norm(read(lf))))
            expr = pkg.get("license") or ""
            c = Component("cargo", pkg["name"], pkg["version"], expr or "UNDECLARED")
            for fn, body in files:
                c.texts.append(Text(fn, body))
            for _fn, body in files:
                for h in holders_in(body):
                    if h not in c.holders:
                        c.holders.append(h)
            ov = manifest.get("cargo_overrides", {}).get(pkg["name"])
            if ov:
                c.notes = ov.get("notes", "")
                for rel in ov.get("extra_texts", []):
                    c.texts.append(Text(rel, norm(read(os.path.join(REPO, rel)))))
                c.holders += [h for h in ov.get("holders", []) if h not in c.holders]
            if not c.holders and pkg.get("authors"):
                c.holders = [", ".join(a.split(" <")[0] for a in pkg["authors"])]
            seen[k] = c
    admit = CARGO_WORKSPACES[0]
    for k, c in seen.items():
        if admit in used_by[k]:
            c.shipped = "shearadmit.node and libshear_admit (wallet, all platforms)"
        else:
            c.shipped = "not in a release binary (dependency of the vendored FCMP++ source)"
    return sorted(seen.values(), key=lambda c: (c.name, c.version))


def npm_components(manifest: dict) -> list[Component]:
    lock = json.loads(read(os.path.join(REPO, "package-lock.json")))["packages"]
    overrides = manifest.get("npm_overrides", {})
    out = []
    for path, meta in sorted(lock.items()):
        if not path:
            continue
        directory = os.path.join(REPO, path)
        pj_path = os.path.join(directory, "package.json")
        if not os.path.isfile(pj_path):
            raise SystemExit(f"{path} is not installed; run npm ci")
        pj = json.loads(read(pj_path))
        name = pj.get("name") or path.split("node_modules/")[-1]
        lic = pj.get("license")
        if lic is None and pj.get("licenses"):
            lic = " OR ".join(x["type"] if isinstance(x, dict) else str(x) for x in pj["licenses"])
        if isinstance(lic, dict):
            lic = lic.get("type")
        c = Component("npm", name, pj.get("version", meta.get("version", "")), lic or "UNDECLARED")
        c.dev = bool(meta.get("dev"))
        for fn, body in license_files(directory):
            c.texts.append(Text(fn, body))
            for h in holders_in(body):
                if h not in c.holders:
                    c.holders.append(h)
        if not c.holders and pj.get("author"):
            a = pj["author"]
            c.holders = [a.get("name", "") if isinstance(a, dict) else str(a).split(" <")[0]]
        ov = overrides.get(name)
        if ov:
            c.license = ov.get("license", c.license)
            c.notes = ov.get("notes", "")
            c.obligation = ov.get("obligation", "")
            for rel in ov.get("extra_texts", []):
                c.texts.append(Text(rel, norm(read(os.path.join(REPO, rel)))))
            c.holders += [h for h in ov.get("holders", []) if h not in c.holders]
        c.shipped = "not shipped (development only)" if c.dev else "node, wallet desktop sidecar and distro packs (node_modules)"
        c.in_notices = not c.dev
        out.append(c)
    return out


def pub_lock() -> dict:
    """Parse the parts of pubspec.lock this script needs without a YAML dependency."""
    pkgs: dict[str, dict] = {}
    cur = None
    for line in read(os.path.join(REPO, "wallet", "pubspec.lock")).split("\n"):
        m = re.match(r"^  ([A-Za-z0-9_]+):$", line)
        if m:
            cur = m.group(1)
            pkgs[cur] = {}
            continue
        if line and not line.startswith(" "):
            cur = None
        if cur is None:
            continue
        m = re.match(r'^    (dependency|source|version): "?([^"]*)"?$', line)
        if m:
            pkgs[cur][m.group(1)] = m.group(2)
    return pkgs


def pub_components(manifest: dict) -> list[Component]:
    cfg_path = os.path.join(REPO, "wallet", ".dart_tool", "package_config.json")
    if not os.path.isfile(cfg_path):
        raise SystemExit("wallet/.dart_tool/package_config.json missing; run flutter pub get in wallet/")
    cfg = json.loads(read(cfg_path))
    lock = pub_lock()
    overrides = manifest.get("pub_overrides", {})
    out = []
    for p in sorted(cfg["packages"], key=lambda p: p["name"]):
        name = p["name"]
        if name in PUB_SDK or name == "shear_wallet" or name not in lock:
            continue
        info = lock[name]
        if info.get("source") == "sdk":
            continue
        uri = p["rootUri"]
        if uri.startswith("file://"):
            directory = uri[len("file://"):]
        else:
            directory = os.path.normpath(os.path.join(os.path.dirname(cfg_path), uri))
        subdirs = tuple(d for d in ("licenses", "LICENSES") if os.path.isdir(os.path.join(directory, d)))
        files = license_files(directory, subdirs)
        if not files:
            raise SystemExit(f"pub package {name} has no licence file in {directory}")
        found: set[str] = set()
        c = Component("pub", name, info.get("version", ""), "")
        for fn, body in files:
            found |= classify(body)
            c.texts.append(Text(fn, body, flutter_collects=(fn == "LICENSE")))
            for h in holders_in(body):
                if h not in c.holders:
                    c.holders.append(h)
        c.license = " AND ".join(sorted(found)) if found else "UNKNOWN"
        c.dev = info.get("dependency") == "direct dev"
        ov = overrides.get(name)
        if ov:
            c.license = ov.get("license", c.license)
            c.notes = ov.get("notes", "")
            for rel in ov.get("extra_texts", []):
                c.texts.append(Text(rel, norm(read(os.path.join(REPO, rel)))))
            c.holders += [h for h in ov.get("holders", []) if h not in c.holders]
        c.shipped = "not shipped (development only)" if c.dev else "wallet (Dart code compiled into every platform build)"
        c.in_notices = not c.dev
        out.append(c)
    return out


ANDROID_LICENSE = (
    (re.compile(r"(?i)apache.*2"), "Apache-2.0"),
    (re.compile(r"(?i)bouncy castle"), "MIT"),
    (re.compile(r"(?i)ml kit terms"), "LicenseRef-MLKit-Terms"),
    (re.compile(r"(?i)android software development kit"), "LicenseRef-Android-SDK-License"),
)


def android_spdx(name: str) -> str:
    parts = []
    for piece in [x.strip() for x in name.split("|")]:
        for pat, spdx in ANDROID_LICENSE:
            if pat.search(piece):
                parts.append(spdx)
                break
        else:
            if re.fullmatch(r"BSD-3-Clause", piece):
                parts.append("BSD-3-Clause")
            elif piece == "NONE-DECLARED":
                parts.append("NONE-DECLARED")
            else:
                parts.append(f"UNKNOWN({piece})")
    return " AND ".join(dict.fromkeys(parts))


def android_components(manifest: dict) -> list[Component]:
    deps = json.loads(read(ANDROID))
    extra = manifest.get("android_overrides", {})
    out = []
    for d in deps["artifacts"]:
        coord = f"{d['group']}:{d['artifact']}"
        c = Component("android", coord, d["version"], android_spdx(d["pom_license"]))
        ov = extra.get(coord) or extra.get(d["group"] + ":*")
        if ov:
            c.license = ov.get("license", c.license)
            c.notes = ov.get("notes", "")
            c.holders = list(ov.get("holders", []))
            for rel in ov.get("texts", []):
                c.texts.append(Text(rel, norm(read(os.path.join(REPO, rel)))))
            if ov.get("in_notices") is False:
                c.in_notices = False
            c.status = ov.get("status", "")
            c.obligation = ov.get("obligation", "")
        if not c.holders and d.get("pom_holders"):
            c.holders = list(d["pom_holders"])
        if not c.texts:
            for i in ids_in(c.license) if not c.license.startswith(("LicenseRef", "NONE", "UNKNOWN")) else []:
                if i in SPDX_TEXT:
                    c.texts.append(spdx_text(i))
        c.shipped = "Android APK"
        out.append(c)
    return out


def manual_components(manifest: dict) -> list[Component]:
    out = []
    for m in manifest["components"]:
        c = Component(m["kind"], m["name"], m.get("version", ""), m["license"])
        c.holders = list(m.get("holders", []))
        c.shipped = m.get("shipped", "")
        c.notes = m.get("notes", "")
        c.obligation = m.get("obligation", "")
        c.status = m.get("status", "")
        c.in_notices = m.get("in_notices", True)
        c.dev = m.get("dev", False)
        for rel in m.get("texts", []):
            c.texts.append(Text(rel, norm(read(os.path.join(REPO, rel)))))
        if m.get("text"):
            c.texts.append(Text("summary", norm(m["text"])))
        out.append(c)
    return out


