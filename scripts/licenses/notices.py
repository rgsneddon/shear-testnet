def policy(components: list[Component], manifest: dict) -> list[str]:
    errors = []
    mpl_ok = manifest["policy"]["mpl_allowed"]
    refs_ok = set(manifest["policy"]["license_refs_allowed"])
    missing_ok = set(manifest["policy"]["missing_license_file_allowed"])
    for c in components:
        expr = c.license
        if c.kind in ("cargo", "npm", "pub"):
            if expr in ("UNDECLARED", "UNKNOWN", ""):
                errors.append(f"{c.key} {c.version}: no declared or recognisable licence")
                continue
            allowed = set(ALLOWED)
            if any(re.fullmatch(p.replace("*", ".*"), c.name) for p in mpl_ok):
                allowed.add("MPL-2.0")
            if c.dev:
                allowed |= {"GPL-3.0-or-later", "GPL-3.0-only", "GPL-3.0"}
            try:
                chosen = elect(expr, allowed)
            except (IndexError, ValueError):
                chosen = None
            if chosen is None:
                bad = sorted(i for i in ids_in(expr) if i not in allowed) if expr else [expr]
                errors.append(f"{c.key} {c.version}: licence {expr} not allowed ({', '.join(bad)})")
                continue
            if not c.obligation:
                c.obligation = obligation_for(chosen)
            if c.in_notices and not c.texts:
                if c.key in missing_ok:
                    for i in chosen:
                        if i in SPDX_TEXT:
                            c.texts.append(spdx_text(i))
                    c.notes = (c.notes + " " if c.notes else "") + "Package ships no licence file; the SPDX text is used."
                else:
                    errors.append(f"{c.key} {c.version}: shipped without a licence file")
            if c.kind == "pub":
                declared = {x for x in ids_in(expr)}
                if "UNKNOWN" in declared:
                    errors.append(f"{c.key}: licence text not recognised")
        elif c.kind == "android":
            for i in ids_in(c.license.replace("(", " ").replace(")", " ")) if c.license else []:
                if i.startswith("UNKNOWN") or (i not in ALLOWED and i not in refs_ok):
                    errors.append(f"{c.key} {c.version}: licence {i} not allowed")
            if c.in_notices and not c.texts:
                errors.append(f"{c.key} {c.version}: no licence text")
            if not c.obligation:
                c.obligation = obligation_for(sorted(ids_in(c.license) & ALLOWED)) if ids_in(c.license) & ALLOWED else "see notes"
        else:
            if c.in_notices and not c.texts:
                errors.append(f"{c.key}: manual component with no licence text")
        if not c.status:
            if c.dev:
                c.status = "OK: development only, not distributed"
            elif not c.in_notices:
                c.status = "OK: covered by Flutter's NOTICES"
            else:
                c.status = "OK: notice in THIRD_PARTY_NOTICES.txt"
    return errors


def pinned_checks(manifest: dict) -> list[str]:
    errors = []
    for rel, digest in manifest["pinned_files"].items():
        p = os.path.join(REPO, rel)
        if not os.path.isfile(p):
            errors.append(f"pinned licence file missing: {rel}")
            continue
        got = hashlib.sha256(open(p, "rb").read()).hexdigest()
        if got != digest:
            errors.append(f"pinned licence file changed: {rel} ({got})")
    for rel in manifest["upstream_headers"]["files"]:
        p = os.path.join(REPO, rel)
        if not os.path.isfile(p):
            errors.append(f"upstream file with a copyright header is gone: {rel}")
            continue
        head = "\n".join(read(p).split("\n")[:40])
        if "Copyright" not in head:
            errors.append(f"upstream copyright header removed from {rel}")
    return errors


PODFILE_LOCK = os.path.join(REPO, "wallet", "ios", "Podfile.lock")


def podfile_lock_trunk_pods(text: str) -> dict[str, str]:
    """{pod: version} for the third-party (trunk) pods in a Podfile.lock."""
    versions: dict[str, str] = {}
    for name, version in re.findall(r"^  - ([^\s(]+) \(([^)]+)\):?$", text, re.M):
        versions.setdefault(name.split("/")[0], version)
    m = re.search(r"^SPEC REPOS:\n  trunk:\n((?:    - .+\n)+)", text, re.M)
    trunk = re.findall(r"^    - (\S+)$", m.group(1), re.M) if m else []
    return {name: versions.get(name, "") for name in trunk}


def ios_pod_checks(manifest: dict) -> list[str]:
    """Every trunk pod in wallet/ios/Podfile.lock needs a reviewed component at that exact version."""
    if not os.path.isfile(PODFILE_LOCK):
        return ["wallet/ios/Podfile.lock is missing; iOS pod versions must be pinned (decision 6)"]
    reviewed = {c["name"]: c["version"].split()[0] for c in manifest["components"] if c["kind"] == "ios"}
    errors = []
    for pod, version in podfile_lock_trunk_pods(read(PODFILE_LOCK)).items():
        if pod not in reviewed:
            errors.append(f"iOS pod {pod} {version} is in Podfile.lock but not in scripts/licenses/components.json")
        elif reviewed[pod] != version:
            errors.append(f"iOS pod {pod}: Podfile.lock has {version}, components.json reviewed {reviewed[pod]}")
    return errors


def attribution_checks() -> list[str]:
    errors = []
    places = {
        "THIRD_PARTY_NOTICES.txt": OUT,
        "wallet/assets/licenses/THIRD_PARTY_NOTICES.txt": WALLET_OUT,
        "docs/licensing-audit.md": AUDIT,
        "README.md": os.path.join(REPO, "README.md"),
        "wallet/lib/shear_licenses.dart": os.path.join(REPO, "wallet", "lib", "shear_licenses.dart"),
    }
    for label, p in places.items():
        if not os.path.isfile(p) or ATTRIBUTION not in read(p):
            errors.append(f"{label} must carry the attribution verbatim: {ATTRIBUTION}")
    return errors


# --- rendering --------------------------------------------------------------

def collect(manifest: dict) -> list[Component]:
    comps = manual_components(manifest)
    comps += cargo_components(manifest)
    comps += npm_components(manifest)
    comps += pub_components(manifest)
    comps += android_components(manifest)
    return comps


KIND_LABEL = {
    "vendored": "vendored source", "manual": "bundled", "cargo": "Rust crate", "npm": "npm",
    "pub": "Dart package", "android": "Android library", "runtime": "bundled runtime",
    "ios": "iOS pod", "asset": "asset", "pointer": "platform",
}


def render_notices(components: list[Component], for_wallet: bool) -> str:
    groups: dict[str, dict] = {}
    order: list[str] = []
    for c in components:
        if not c.in_notices:
            continue
        for t in c.texts:
            if for_wallet and t.flutter_collects:
                continue
            h = hashlib.sha256(t.body.encode()).hexdigest()
            if h not in groups:
                groups[h] = {"body": t.body, "names": [], "comps": [], "licenses": [], "files": []}
                order.append(h)
            g = groups[h]
            label = f"{c.name} {c.version} ({KIND_LABEL.get(c.kind, c.kind)})".replace("  ", " ")
            if label not in g["comps"]:
                g["comps"].append(label)
            if c.name not in g["names"]:
                g["names"].append(c.name)
            if c.license not in g["licenses"]:
                g["licenses"].append(c.license)
            if t.label not in g["files"]:
                g["files"].append(t.label)
    parts = [
        "Shear third-party notices",
        "",
        "Generated by scripts/licenses/notices.py. Do not edit by hand.",
        "Shear is MIT licensed (see the Shear section). Each section below names the",
        "components it covers and carries the licence text and copyright lines exactly",
        "as each component ships them.",
        "",
        RULE,
        "PACKAGES: Shear",
        "COMPONENTS: Shear (attribution)",
        "LICENSE: Attribution (not a licence grant)",
        SUB,
        "ATTRIBUTION",
        "",
        ATTRIBUTION,
        "",
        "This is an attribution. It grants no licence and adds no terms to any component.",
        "",
        RULE,
        "PACKAGES: Shear",
        "COMPONENTS: Shear",
        "LICENSE: MIT",
        SUB,
        norm(read(os.path.join(REPO, "LICENSE"))),
        "",
    ]
    for h in order:
        g = groups[h]
        parts += [
            RULE,
            "PACKAGES: " + "; ".join(g["names"]),
            "COMPONENTS: " + "; ".join(g["comps"]),
            "LICENSE: " + "; ".join(g["licenses"]),
            "FILE: " + "; ".join(g["files"]),
            SUB,
            g["body"],
            "",
        ]
    return "\n".join(parts).rstrip("\n") + "\n"


def md_escape(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def render_inventory(components: list[Component]) -> str:
    rows = [
        BEGIN,
        "",
        f"{len(components)} components. Kinds: vendored source, bundled runtime, Rust crate, npm, Dart package, Android library, iOS pod, asset, platform.",
        "",
        "| Kind | Component | Version | Licence | Copyright holders | Shipped in | Obligation | Status |",
        "|---|---|---|---|---|---|---|---|",
    ]
    kind_order = {"vendored": 0, "runtime": 1, "manual": 1, "ios": 2, "pointer": 3, "asset": 4, "cargo": 5, "npm": 6, "pub": 7, "android": 8}
    for c in sorted(components, key=lambda c: (kind_order.get(c.kind, 9), c.name.lower(), c.version)):
        holders = c.holders[:3] if c.in_notices else c.holders
        more = len(c.holders) - len(holders)
        h = "; ".join(holders) + (f"; +{more} more in THIRD_PARTY_NOTICES.txt" if more > 0 else "")
        status = c.status + (f". {c.notes}" if c.notes and c.status.startswith("OK") else "")
        rows.append("| " + " | ".join(md_escape(x) for x in (
            KIND_LABEL.get(c.kind, c.kind), c.name, c.version or "-", c.license, h or "none stated",
            c.shipped, c.obligation, status,
        )) + " |")
    rows += ["", END]
    return "\n".join(rows)


def splice_audit(text: str, inventory: str) -> str:
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{AUDIT} must contain the inventory markers")
    head = text.split(BEGIN, 1)[0]
    tail = text.split(END, 1)[1]
    return head + inventory + tail


def build() -> tuple[dict[str, str], list[str]]:
    manifest = json.loads(read(MANIFEST))
    comps = collect(manifest)
    errors = policy(comps, manifest)
    errors += pinned_checks(manifest)
    errors += ios_pod_checks(manifest)
    outputs = {
        OUT: render_notices(comps, for_wallet=False),
        WALLET_OUT: render_notices(comps, for_wallet=True),
    }
    if os.path.isfile(AUDIT):
        outputs[AUDIT] = splice_audit(read(AUDIT), render_inventory(comps))
    return outputs, errors


def write(path: str, body: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)


# --- android-sync -----------------------------------------------------------

def android_sync(deps_txt: str) -> None:
    text = read(deps_txt)
    section = text.split("releaseRuntimeClasspath", 1)[1] if "releaseRuntimeClasspath" in text else text
    section = section.split("\n\n", 1)[0]
    coords: dict[str, str] = {}
    for line in section.split("\n"):
        m = re.search(r"[+\\]--- ([A-Za-z0-9_.\-]+):([A-Za-z0-9_.\-]+):([^\s]+)(?: -> ([^\s]+))?", line)
        if not m:
            continue
        g, a, v, resolved = m.group(1), m.group(2), m.group(3), m.group(4)
        coords[f"{g}:{a}"] = resolved or v
    cache = os.path.expanduser("~/.gradle/caches/modules-2/files-2.1")

    def pom_licenses(g: str, a: str, v: str, depth: int = 0) -> list[str]:
        poms = glob.glob(os.path.join(cache, g, a, v, "*", f"{a}-{v}.pom"))
        if not poms or depth > 5:
            return [], []
        try:
            root = ET.parse(poms[0]).getroot()
        except ET.ParseError:
            return [], []
        pre = "{" + root.tag.split("}")[0][1:] + "}" if root.tag.startswith("{") else ""
        lic = root.find(f"{pre}licenses")
        names = [e.text.strip() for e in lic.iter(f"{pre}name") if e.text] if lic is not None else []
        holders = []
        org = root.findtext(f"{pre}organization/{pre}name")
        if org:
            holders.append(org.strip())
        for dev in root.findall(f"{pre}developers/{pre}developer"):
            who = (dev.findtext(f"{pre}organization") or dev.findtext(f"{pre}name") or "").strip()
            if who and who not in holders:
                holders.append(who)
        if names:
            return names, holders
        parent = root.find(f"{pre}parent")
        if parent is None:
            return [], holders
        pg, pa, pv = (parent.findtext(f"{pre}{t}") for t in ("groupId", "artifactId", "version"))
        if not (pg and pa and pv):
            return [], holders
        pnames, pholders = pom_licenses(pg, pa, pv, depth + 1)
        return pnames, holders or pholders

    artifacts = []
    for coord in sorted(coords):
        g, a = coord.split(":")
        v = coords[coord]
        names, holders = pom_licenses(g, a, v)
        artifacts.append({"group": g, "artifact": a, "version": v, "pom_license": " | ".join(names) or "NONE-DECLARED",
                          "pom_holders": holders})
    write(ANDROID, json.dumps({
        "source": "./gradlew :app:dependencies --configuration releaseRuntimeClasspath (wallet/android); licences from each artifact's POM",
        "artifacts": artifacts,
    }, indent=1) + "\n")
    print("wrote", ANDROID, len(artifacts), "artifacts")


def main(argv: list[str]) -> int:
    if not argv or argv[0] not in ("generate", "check", "android-sync"):
        print(__doc__)
        return 2
    if argv[0] == "android-sync":
        android_sync(argv[1])
        return 0
    outputs, errors = build()
    if argv[0] == "generate":
        for path, body in outputs.items():
            write(path, body)
            print("wrote", os.path.relpath(path, REPO))
    else:
        for path, body in outputs.items():
            if not os.path.isfile(path) or read(path) != body:
                errors.append(f"{os.path.relpath(path, REPO)} is stale; run python3 scripts/licenses/notices.py generate")
    errors += attribution_checks()
    misspelt = "Chronoflux " + "Princip" + "is"
    stray = subprocess.run(["git", "grep", "-l", misspelt], cwd=REPO, capture_output=True, text=True).stdout.split()
    if stray:
        errors.append("misspelt attribution (Principis) in " + ", ".join(stray))
    if errors:
        for e in errors:
            print("licence check:", e, file=sys.stderr)
        return 1
    print("licence check ok" if argv[0] == "check" else "generated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
