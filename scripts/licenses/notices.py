# --- SPDX expressions -------------------------------------------------------

def tokenize(expr: str) -> list[str]:
    expr = expr.replace("/", " OR ")
    return re.findall(r"\(|\)|[A-Za-z0-9.+:-]+", expr)


def parse(expr: str):
    toks = tokenize(expr)
    pos = 0

    def atom():
        nonlocal pos
        if toks[pos] == "(":
            pos += 1
            node = disj()
            pos += 1
            return node
        ident = toks[pos]
        pos += 1
        if pos < len(toks) and toks[pos] == "WITH":
            ident = f"{ident} WITH {toks[pos + 1]}"
            pos += 2
        return ("id", ident)

    def conj():
        nonlocal pos
        parts = [atom()]
        while pos < len(toks) and toks[pos] == "AND":
            pos += 1
            parts.append(atom())
        return ("and", parts) if len(parts) > 1 else parts[0]

    def disj():
        nonlocal pos
        parts = [conj()]
        while pos < len(toks) and toks[pos] == "OR":
            pos += 1
            parts.append(conj())
        return ("or", parts) if len(parts) > 1 else parts[0]

    return disj()


def elect(expr: str, allowed: set[str]) -> list[str] | None:
    """Licences Shear takes the component under, or None if the allow list cannot satisfy expr."""

    def rank(ids: list[str]) -> tuple:
        return tuple(sorted(PREFERENCE.index(i) if i in PREFERENCE else 99 for i in ids))

    def ev(node):
        if node[0] == "id":
            return [node[1]] if node[1] in allowed else None
        results = [ev(p) for p in node[1]]
        if node[0] == "and":
            if any(r is None for r in results):
                return None
            return sorted({i for r in results for i in r})
        ok = [r for r in results if r is not None]
        return min(ok, key=lambda r: (len(r), rank(r))) if ok else None

    return ev(parse(expr))


def ids_in(expr: str) -> set[str]:
    out = set()

    def walk(node):
        if node[0] == "id":
            out.add(node[1])
        else:
            for p in node[1]:
                walk(p)

    walk(parse(expr))
    return out


# --- licence text helpers ---------------------------------------------------

def classify(text: str) -> set[str]:
    t = " ".join(text.split())
    found = set()
    if "Apache License" in t and ("Version 2.0" in t or "LICENSE-2.0" in t):
        found.add("Apache-2.0")
    if "Permission is hereby granted, free of charge" in t:
        found.add("MIT" if "shall be included in all copies" in t else "MIT-0")
    if "Redistribution and use in source and binary forms" in t:
        if re.search(r"(?i)neither the name|names of (its|the) contributors|name of the copyright holder", t):
            found.add("BSD-3-Clause")
        elif re.search(r"(?i)binary form must reproduce", t):
            found.add("BSD-2-Clause")
        else:
            found.add("BSD-1-Clause")
    if re.search(r"Permission to use, copy, modify, and(/or)? distribute this software for any purpose", t):
        found.add("ISC")
    if "Mozilla Public License" in t:
        found.add("MPL-2.0")
    if "GNU LESSER GENERAL PUBLIC" in t.upper():
        found.add("LGPL")
    elif "GNU AFFERO GENERAL PUBLIC" in t.upper():
        found.add("AGPL")
    elif "GNU GENERAL PUBLIC LICENSE" in t.upper():
        found.add("GPL")
    if "This is free and unencumbered software released into the public domain" in t:
        found.add("Unlicense")
    if "CC0 1.0 Universal" in t or "CC0 Public Domain Dedication" in t:
        found.add("CC0-1.0")
    if "altered source versions must be plainly marked" in t.lower():
        found.add("Zlib")
    if "UNICODE LICENSE" in t.upper() and "UNICODE, INC." in t.upper():
        found.add("Unicode-3.0")
    return found


COPYRIGHT_LINE = re.compile(r"(?i)^\s*(?:[*#/;\-]+\s*)?((?:copyright|\(c\)|©).*)$")
TEMPLATE = re.compile(r"(?i)\[yyyy\]|<year>|\{yyyy\}|\[name of copyright owner\]|<copyright holders>|"
                      r"copyright notice|copyright owner|copyright holders? (and|or)|copyright license|"
                      r"copyright law|copyright, patent|copyright and|copyright (is|in|to|statement)|"
                      r"\(c\) (you|the|each|if|any)|<organization>|copyright \(c\) <|^copyrights in|copyright assignment")


def holders_in(text: str) -> list[str]:
    out = []
    for line in text.split("\n"):
        m = COPYRIGHT_LINE.match(line)
        if not m:
            continue
        s = " ".join(m.group(1).split())
        if TEMPLATE.search(s) or re.match(r"(?i)copyright holders\b", s):
            continue
        if not s.lower().startswith("copyright") and not re.search(r"\d{4}", s):
            continue
        if not re.search(r"\d{4}|[A-Za-z]{3,}", s[9:] if s.lower().startswith("copyright") else s):
            continue
        if len(s) > 160:
            continue
        if s not in out:
            out.append(s)
    return out


def license_files(directory: str, recursive_dirs: tuple[str, ...] = ()) -> list[tuple[str, str]]:
    """(relative name, normalised text) for licence files at the top of directory."""
    out = []
    if not os.path.isdir(directory):
        return out
    for fn in sorted(os.listdir(directory)):
        p = os.path.join(directory, fn)
        if os.path.isfile(p) and LICENSE_FILE.match(fn) and not fn.lower().startswith("authors"):
            out.append((fn, norm(read(p))))
    for sub in recursive_dirs:
        root = os.path.join(directory, sub)
        for dp, dns, fns in os.walk(root):
            dns.sort()
            for fn in sorted(fns):
                p = os.path.join(dp, fn)
                body = read(p)
                if fn.lower().endswith((".html", ".htm")):
                    body = html_to_text(body)
                out.append((os.path.relpath(p, directory).replace("\\", "/"), norm(body)))
    return out


def html_to_text(html: str) -> str:
    html = re.sub(r"(?is)<(script|style).*?</\1>", "", html)
    html = re.sub(r"(?i)<br\s*/?>|</p>|</h\d>|</li>|</tr>", "\n", html)
    html = re.sub(r"(?s)<[^>]+>", "", html)
    for a, b in (("&nbsp;", " "), ("&lt;", "<"), ("&gt;", ">"), ("&quot;", '"'), ("&#39;", "'"), ("&copy;", "©"), ("&amp;", "&")):
        html = html.replace(a, b)
    return re.sub(r"\n{3,}", "\n\n", html)


def obligation_for(ids: list[str]) -> str:
    parts = []
    s = set(ids)
    if s & {"MIT", "ISC", "BSD-2-Clause", "BSD-1-Clause", "Zlib", "Unicode-3.0", "BSD-3-Clause"}:
        parts.append("keep the copyright and licence text in source and binary copies")
    if "BSD-3-Clause" in s:
        parts.append("no endorsement using the holders' names")
    if s & {"Apache-2.0", "Apache-2.0 WITH LLVM-exception"}:
        parts.append("ship the Apache-2.0 text and any NOTICE; mark modified files")
    if "MPL-2.0" in s:
        parts.append("MPL-2.0 file-level copyleft: ship the licence and keep the source of those files available (npm ships them as source); changes to them stay MPL-2.0")
    if s and s <= {"CC0-1.0", "MIT-0", "Unlicense"}:
        parts.append("none (credited as a courtesy)")
    return "; ".join(parts) or "see licence"


