/**
 * Write wallet/lib/shear_chain_params.dart from crypto/chain_params.js.
 * Fingerprint shas are the sha256 of consensusFingerprint for each table key.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { CHAIN_PARAMS, canonicalParamsJson } from '../crypto/chain_params.js';
import { consensusFingerprint, mainnetFingerprint } from '../crypto/asert.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'wallet', 'lib', 'shear_chain_params.dart');

const order = ['shear-dev', 'shear-testnet-v12', 'shear-v1'];
const fp = {
  'shear-dev': createHash('sha256').update(consensusFingerprint('shear-dev')).digest('hex'),
  'shear-testnet-v12': createHash('sha256').update(consensusFingerprint('shear-testnet-v12')).digest('hex'),
  'shear-v1': createHash('sha256').update(mainnetFingerprint()).digest('hex'),
};

function dartValue(value) {
  if (typeof value === 'string') return `'${value}'`;
  if (typeof value === 'number') return String(value);
  if (Array.isArray(value)) {
    if (!value.length) return 'const <String>[]';
    return `const <String>[${value.map((v) => `'${v}'`).join(', ')}]`;
  }
  throw new Error(`unsupported ${typeof value}`);
}

const sample = CHAIN_PARAMS['shear-testnet-v12'];
const fields = Object.keys(sample);
const stringFields = new Set(fields.filter((k) => typeof sample[k] === 'string'));
const listFields = new Set(fields.filter((k) => Array.isArray(sample[k])));

const classFields = fields.map((name) => {
  const type = listFields.has(name) ? 'List<String>' : (stringFields.has(name) ? 'String' : 'int');
  return `  final ${type} ${name};`;
}).join('\n');

const ctorArgs = fields.map((name) => `    required this.${name},`).join('\n');

function rowLiteral(magic) {
  const spec = CHAIN_PARAMS[magic];
  const args = fields.map((name) => `      ${name}: ${dartValue(spec[name])},`).join('\n');
  return `  '${magic}': ShearChainRow(\n${args}\n  )`;
}

const json = order.map((magic) => canonicalParamsJson(magic)).join('\n');

const dart = `// Generated by scripts/gen_chain_params_dart.mjs. Do not edit by hand.
// CHAIN_PARAMS_JSON_BEGIN
${json}
// CHAIN_PARAMS_JSON_END

class ShearChainRow {
${classFields}

  const ShearChainRow({
${ctorArgs}
  });
}

const Map<String, ShearChainRow> kChainParams = {
${order.map(rowLiteral).join(',\n')},
};

const Map<String, String> kFingerprintShaByMagic = {
  'shear-dev': '${fp['shear-dev']}',
  'shear-testnet-v12': '${fp['shear-testnet-v12']}',
  'shear-v1': '${fp['shear-v1']}',
};

const String kDevFingerprintSha = '${fp['shear-dev']}';
`;

fs.writeFileSync(out, dart);
console.log(out);
console.log(JSON.stringify(fp));
