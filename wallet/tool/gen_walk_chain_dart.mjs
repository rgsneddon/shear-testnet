// Turn the mined chain (tool/gen_walk_chain.mjs) into
// integration_test/walk_chain_data.dart for the walk-frames build. The pin
// is the ShearHash-v3 digest of the last header, computed here with the
// node's own hash; the walk links down to height 1 from it.
//   node wallet/tool/gen_walk_chain_dart.mjs <chain.bin> <out.dart> [headers]
// The output is generated, gitignored, and is never part of a release build.
import fs from 'node:fs';
import { shearHash, setHashBackend } from '../../crypto/shear_hash.js';

try { setHashBackend('jit'); } catch { /* interpreter */ }
const [src, out, want] = process.argv.slice(2);
const all = fs.readFileSync(src);
let n = Math.floor(all.length / 128);
if (want) n = Math.min(n, Math.floor(Number(want)));
if (n < 11) throw new Error(`only ${n} headers`);
const chain = all.subarray(0, n * 128);
const tsAt = (h) => Number(chain.readBigUInt64LE((h - 1) * 128 + 100));
const pin = {
  network: 'regtest-walk-frames',
  height: n,
  hashHex: shearHash(chain.subarray((n - 1) * 128, n * 128)).toString('hex'),
  timeMs: tsAt(n),
  bits: chain.readUInt32LE((n - 1) * 128 + 108),
  anchorHeight: 1,
  anchorTimeMs: tsAt(1),
  anchorBits: 17 * 65536,
  priorTimesMs: Array.from({ length: 10 }, (_, i) => tsAt(n - 10 + i)),
};
const b64 = chain.toString('base64');
const chunks = [];
for (let i = 0; i < b64.length; i += 60000) chunks.push(b64.slice(i, i + 60000));
const lines = [
  '// GENERATED by tool/gen_walk_chain_dart.mjs: a mined, linking regtest',
  `// header chain of ${n} headers. Walk-frames build only. Do not edit.`,
  `const Map<String, Object> kWalkPin = ${JSON.stringify(pin)};`,
  'const List<String> kWalkChainChunks = <String>[',
  ...chunks.map((c) => `  '${c}',`),
  '];',
  '',
];
fs.writeFileSync(out, lines.join('\n'));
process.stdout.write(`wrote ${out}: ${n} headers, pin ${pin.hashHex}\n`);
